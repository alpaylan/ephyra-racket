#!/usr/bin/env python3
"""numref: independent reference evaluator for the `numref` oracle.

A numref program (generated by rktgen, gen/src/num.rs) is a Racket module

  (module m racket/base (require racket/flonum racket/fixnum)
    (define q ...) (define (enc v) ...) (define (o i th) ...)
    (define (f3 p0 p1) <expr>) ...          ; optional per-line functions
    (o 0 (lambda () <expr>)) ...)

Each `(o i (lambda () e))` prints "i <enc of e's value>" or "i err" when e
raised exn:fail.  This script parses the same text, evaluates every e with
Python ints / fractions.Fraction / IEEE doubles following the Racket
reference (numbers.scrbl, flonums.scrbl, fixnums.scrbl), and compares with
the result line runner.rkt printed for the machine-code run.

  numref.py eval prog.rkt            expected lines
  numref.py check prog.rkt < line    exit 1 mismatch, 0 match, 2 undecidable
  numref.py server                   framed "<n>\n<prog><m>\n<line>" -> verdict line
"""
import sys, math, struct, ctypes, re
from fractions import Fraction

FXMIN, FXMAX = -(1 << 60), (1 << 60) - 1
M61 = (1 << 61) - 1


class Err(Exception):
    pass


class Unspec(Exception):
    pass


# ---------------------------------------------------------------- reader
class Sym(str):
    pass


TOK = re.compile(r"""\s+|;[^\n]*|[()\[\]']|"(?:[^"\\]|\\.)*"|[^\s()\[\]";']+""")


def parse_all(text):
    toks = [t for t in TOK.findall(text) if t.strip() and not t.startswith(';')]
    pos = 0

    def rd():
        nonlocal pos
        t = toks[pos]; pos += 1
        if t == "'":
            return [Sym('quote'), rd()]
        if t in '([':
            l = []
            while toks[pos] not in ')]':
                l.append(rd())
            pos += 1
            return l
        if t.startswith('"'):
            return t[1:-1].encode().decode('unicode_escape')
        return atom(t)
    out = []
    while pos < len(toks):
        out.append(rd())
    return out


RAT = re.compile(r'^[+-]?\d+/\d+$')
INT = re.compile(r'^[+-]?\d+$')
FLT = re.compile(r'^[+-]?(\d+\.?\d*|\.\d+)([eE][+-]?\d+)?$')


def atom(t):
    if t == '#t': return True
    if t == '#f': return False
    if t == '+inf.0': return math.inf
    if t == '-inf.0': return -math.inf
    if t in ('+nan.0', '-nan.0'): return math.nan
    if INT.match(t): return int(t)
    if RAT.match(t): return norm(Fraction(t))
    if FLT.match(t): return float(t)
    return Sym(t)


def norm(x):
    if isinstance(x, Fraction) and x.denominator == 1:
        return int(x.numerator)
    return x


# ---------------------------------------------------------------- types
def isfl(x): return isinstance(x, float)
def isbool(x): return isinstance(x, bool)
def isexact(x): return (isinstance(x, int) and not isinstance(x, bool)) or isinstance(x, Fraction)
def isint(x): return isinstance(x, int) and not isinstance(x, bool)
def isfx(x): return isint(x) and FXMIN <= x <= FXMAX


def need(c):
    if not c:
        raise Err()


def fxres(x):
    need(FXMIN <= x <= FXMAX)
    return x


def wrap61(x):
    x &= M61
    return x - (1 << 61) if x >> 60 else x


def ieee_div(a, b):
    if b == 0.0:
        if a == 0.0 or math.isnan(a):
            return math.nan
        return math.copysign(math.inf, a) * math.copysign(1.0, b)
    return a / b


def fl_sqrt(a):
    if math.isnan(a) or a < 0: return math.nan
    return math.sqrt(a)


def fl_round_like(a, f):
    if math.isnan(a) or math.isinf(a): return a
    r = f(Fraction(a))
    if r == 0: return math.copysign(0.0, a)
    return float(r)


def round_even(x):  # Fraction -> int, ties to even
    return round(x)


def to_inexact(x):
    if isfl(x): return x
    try:
        return float(x)
    except OverflowError:
        return math.inf if x > 0 else -math.inf


def to_exact(x):
    if isexact(x): return x
    need(not (math.isnan(x) or math.isinf(x)))
    return norm(Fraction(x))


def fl_minmax(args, ismax):
    for a in args: need(isfl(a))
    if any(math.isnan(a) for a in args): return math.nan
    r = args[0]
    for a in args[1:]:
        if a == r == 0.0:
            # 05afec9201 "flmax: always return second argument for 0.0 and -0.0 ...
            # for consistency with flmin, min, and max"
            r = a
        elif (a > r) if ismax else (a < r):
            r = a
    return r


def flsingle(a):
    if math.isnan(a): return a
    return float(ctypes.c_float(a).value)


def flbits(a):
    if math.isnan(a): raise Unspec()
    return struct.unpack('<Q', struct.pack('<d', a))[0]


def tquot(a, b):
    need(b != 0)
    q = abs(a) // abs(b)
    return q if (a >= 0) == (b >= 0) else -q


def num2str(x, r):
    def d(n):
        if n == 0: return '0'
        s = ''
        m = abs(n)
        while m:
            s = '0123456789abcdef'[m % r] + s
            m //= r
        return ('-' if n < 0 else '') + s
    if isint(x): return d(x)
    if isinstance(x, Fraction): return d(x.numerator) + '/' + d(x.denominator)
    raise Unspec()


def str2num(s, r):
    try:
        if '/' in s:
            a, b = s.split('/')
            bb = int(b, r)
            if bb == 0: return False
            return norm(Fraction(int(a, r), bb))
        return int(s, r)
    except ValueError:
        return False


def generic2(op, a, b):
    if isexact(a) and isexact(b):
        if op == '+': return norm(Fraction(a) + b) if not (isint(a) and isint(b)) else a + b
        if op == '-': return norm(Fraction(a) - b) if not (isint(a) and isint(b)) else a - b
        if op == '*': return norm(Fraction(a) * b) if not (isint(a) and isint(b)) else a * b
        if op == '/':
            need(b != 0)
            return norm(Fraction(a) / b)
    if isfl(a) and isfl(b):
        if op == '+': return a + b
        if op == '-': return a - b
        if op == '*': return a * b
        if op == '/': return ieee_div(a, b)
    raise Unspec()


def cmp_chain(f, args):
    for a in args: need(isexact(a) or isfl(a))
    return all(f(args[i], args[i + 1]) for i in range(len(args) - 1))


def unary_real_round(name, a):
    fs = {'floor': math.floor, 'ceiling': math.ceil, 'round': round_even,
          'truncate': lambda x: int(x)}
    f = fs[name]
    if isfl(a): return fl_round_like(a, f)
    if isint(a): return a
    if isinstance(a, Fraction): return int(f(a))
    raise Err()


def prim(name, a):
    n = len(a)
    if name in ('+', '-', '*', '/') and n == 2: return generic2(name, a[0], a[1])
    if name == '-' and n == 1:
        need(isexact(a[0]) or isfl(a[0])); return norm(-a[0]) if isexact(a[0]) else -a[0]
    if name in ('=', '<', '>', '<=', '>='):
        f = {'=': lambda x, y: x == y, '<': lambda x, y: x < y, '>': lambda x, y: x > y,
             '<=': lambda x, y: x <= y, '>=': lambda x, y: x >= y}[name]
        return cmp_chain(f, a)
    if name in ('max', 'min'):
        for x in a: need(isexact(x))
        return max(a) if name == 'max' else min(a)
    if name in ('quotient', 'remainder', 'modulo'):
        x, y = a; need(isint(x) and isint(y)); need(y != 0)
        if name == 'quotient': return tquot(x, y)
        if name == 'remainder': return x - y * tquot(x, y)
        return x % y
    if name in ('gcd', 'lcm'):
        # numbers.scrbl: "for non-integer ns, the result is the gcd of the numerators
        # divided by the lcm of the denominators" (lcm: lcm of numerators / gcd of denominators)
        need(all(isexact(x) for x in a))
        ns = [Fraction(x).numerator for x in a]; ds = [Fraction(x).denominator for x in a]
        if name == 'gcd': return norm(Fraction(math.gcd(*ns), math.lcm(*ds)))
        if any(x == 0 for x in ns): return 0
        return norm(Fraction(abs(math.lcm(*ns)), math.gcd(*ds)))
    if name == 'abs': need(isexact(a[0]) or isfl(a[0])); return abs(a[0])
    if name == 'add1': need(isexact(a[0])); return norm(a[0] + 1)
    if name == 'sub1': need(isexact(a[0])); return norm(a[0] - 1)
    if name == 'expt':
        b, e = a; need(isexact(b) and isint(e))
        if e < 0:
            need(b != 0); return norm(Fraction(1) / (Fraction(b) ** -e))
        return norm(Fraction(b) ** e) if isinstance(b, Fraction) else b ** e
    if name == 'arithmetic-shift':
        x, k = a; need(isint(x) and isint(k))
        return x << k if k >= 0 else x >> -k
    if name == 'bitwise-and': need(all(isint(x) for x in a)); r = -1; [r := r & x for x in a]; return r
    if name == 'bitwise-ior': need(all(isint(x) for x in a)); r = 0; [r := r | x for x in a]; return r
    if name == 'bitwise-xor': need(all(isint(x) for x in a)); r = 0; [r := r ^ x for x in a]; return r
    if name == 'bitwise-not': need(isint(a[0])); return ~a[0]
    if name == 'integer-length': need(isint(a[0])); x = a[0]; return (x if x >= 0 else ~x).bit_length()
    if name == 'bitwise-bit-set?': x, k = a; need(isint(x) and isint(k) and k >= 0); return bool((x >> k) & 1)
    if name == 'bitwise-bit-field':
        x, s, e = a; need(isint(x) and 0 <= s <= e); return (x >> s) & ((1 << (e - s)) - 1)
    if name == 'bitwise-first-bit-set':
        x = a[0]; need(isint(x)); return -1 if x == 0 else (x & -x).bit_length() - 1
    if name == 'integer-sqrt': x = a[0]; need(isint(x) and x >= 0); return math.isqrt(x)
    if name == 'numerator': need(isexact(a[0])); return Fraction(a[0]).numerator
    if name == 'denominator': need(isexact(a[0])); return Fraction(a[0]).denominator
    if name in ('floor', 'ceiling', 'round', 'truncate'): return unary_real_round(name, a[0])
    if name == 'exact->inexact': need(isexact(a[0]) or isfl(a[0])); return to_inexact(a[0])
    if name == 'inexact->exact': need(isexact(a[0]) or isfl(a[0])); return to_exact(a[0])
    if name in ('even?', 'odd?'):
        x = a[0]; need(isint(x)); return (x % 2 == 0) == (name == 'even?')
    if name == 'zero?': need(isexact(a[0]) or isfl(a[0])); return a[0] == 0
    if name == 'positive?': need(isexact(a[0]) or isfl(a[0])); return a[0] > 0
    if name == 'negative?': need(isexact(a[0]) or isfl(a[0])); return a[0] < 0
    if name == 'number->string':
        x = a[0]; r = a[1] if n > 1 else 10; need(isexact(x)); return num2str(x, r)
    if name == 'string->number':
        s = a[0]; r = a[1] if n > 1 else 10; need(isinstance(s, str)); return str2num(s, r)
    if name == 'sqrt':
        x = a[0]; need(isexact(x) or isfl(x))
        if isexact(x) and x >= 0:
            fr = Fraction(x); n, d = math.isqrt(fr.numerator), math.isqrt(fr.denominator)
            if n * n == fr.numerator and d * d == fr.denominator: return norm(Fraction(n, d))
        raise Unspec()  # inexact result: rounding not specified; negative: complex
    if name == 'integer->integer-bytes':
        x, n, sg, be = a; need(isint(x) and n in (1, 2, 4, 8))
        try:
            return x.to_bytes(n, 'big' if be is not False else 'little', signed=sg is not False)
        except OverflowError:
            raise Err()
    if name == 'integer-bytes->integer':
        b, sg, be = a; need(isinstance(b, bytes))
        return int.from_bytes(b, 'big' if be is not False else 'little', signed=sg is not False)
    if name == 'real->floating-point-bytes':
        x, n, be = a; need(isfl(x) and n in (4, 8))
        if n == 4: x = flsingle(x)
        if math.isnan(x): return ('nan', n, be is not False)
        return struct.pack(('>' if be is not False else '<') + ('f' if n == 4 else 'd'), x)
    if name == 'floating-point-bytes->real':
        b, be = a
        if isinstance(b, tuple):
            if b[2] != (be is not False): raise Unspec()  # NaN payload bytes reversed
            return math.nan
        return struct.unpack(('>' if be is not False else '<') + ('f' if len(b) == 4 else 'd'), b)[0]
    # flonums
    if name.startswith('fl') or name in ('->fl',):
        return flprim(name, a)
    if name.startswith('fx'):
        return fxprim(name, a)
    if name == 'not': return a[0] is False
    raise Unspec()


def flprim(name, a):
    if name == '->fl': need(isint(a[0])); return to_inexact(a[0])
    if name == 'fl->exact-integer':
        x = a[0]; need(isfl(x) and not math.isnan(x) and not math.isinf(x) and x == math.floor(x))
        return int(Fraction(x))
    if name == 'fl->fx':
        x = a[0]; need(isfl(x) and not math.isnan(x) and not math.isinf(x))
        return fxres(int(Fraction(x)))
    if name == 'flbit-field':
        x, s, e = a; need(isfl(x) and 0 <= s <= e <= 64); return (flbits(x) >> s) & ((1 << (e - s)) - 1)
    for x in a: need(isfl(x))
    if name == 'fl+': r = 0.0 if not a else a[0]; [r := r + x for x in a[1:]]; return r if a else 0.0
    if name == 'fl*': r = 1.0 if not a else a[0]; [r := r * x for x in a[1:]]; return r
    if name == 'fl-':
        if len(a) == 1: return -a[0]
        r = a[0]; [r := r - x for x in a[1:]]; return r
    if name == 'fl/':
        if len(a) == 1: return ieee_div(1.0, a[0])
        r = a[0]; [r := ieee_div(r, x) for x in a[1:]]; return r
    if name == 'flabs': return abs(a[0])
    if name == 'flsqrt': return fl_sqrt(a[0])
    if name == 'flsingle': return flsingle(a[0])
    if name in ('flround', 'flfloor', 'flceiling', 'fltruncate'):
        return unary_real_round(name[2:], a[0])
    if name in ('flmin', 'flmax'): return fl_minmax(a, name == 'flmax')
    if name == 'flfma': return fma(*a)
    if name == 'flnextafter': return nextafter(*a)
    if name in ('fl=', 'fl<', 'fl>', 'fl<=', 'fl>='): return prim(name[2:], a)
    raise Unspec()


def fxprim(name, a):
    if name == 'fx->fl': need(isfx(a[0])); return to_inexact(a[0])
    for x in a: need(isfx(x))
    if name == 'fx+': return fxres(sum(a))
    if name == 'fx-': return fxres(-a[0] if len(a) == 1 else a[0] - sum(a[1:]))
    if name == 'fx*':
        r = 1
        for x in a: r *= x
        return fxres(r)
    if name in ('fxquotient', 'fxremainder', 'fxmodulo'):
        return fxres(prim(name[2:], a))
    if name == 'fxabs': return fxres(abs(a[0]))
    if name in ('fxand', 'fxior', 'fxxor', 'fxnot'):
        return prim('bitwise-' + name[2:], a)
    if name == 'fxlshift':
        x, k = a; need(0 <= k <= 60); return fxres(x << k)
    if name == 'fxrshift':
        x, k = a; need(0 <= k <= 60); return x >> k
    if name == 'fxrshift/logical':
        x, k = a; need(0 <= k <= 61); return wrap61((x & M61) >> k)
    if name == 'fx+/wraparound': return wrap61(a[0] + a[1])
    if name == 'fx-/wraparound': return wrap61(-a[0] if len(a) == 1 else a[0] - a[1])
    if name == 'fx*/wraparound': return wrap61(a[0] * a[1])
    if name == 'fxlshift/wraparound':
        x, k = a; need(0 <= k <= 61); return wrap61(x << k)
    if name == 'fxpopcount': need(a[0] >= 0); return bin(a[0]).count('1')
    if name == 'fxpopcount32': need(0 <= a[0] <= 0xFFFFFFFF); return bin(a[0]).count('1')
    if name == 'fxpopcount16': need(0 <= a[0] <= 0xFFFF); return bin(a[0]).count('1')
    if name in ('fxmin', 'fxmax'): return min(a) if name == 'fxmin' else max(a)
    if name in ('fx=', 'fx<', 'fx>', 'fx<=', 'fx>='): return prim(name[2:], a)
    raise Unspec()


# ---------------------------------------------------------------- Chez lines
CHEZ = {'fxsll': 'fxlshift', 'fxsra': 'fxrshift', 'fxsrl': 'fxrshift/logical',
        'fxsll/wraparound': 'fxlshift/wraparound', 'flonum->fixnum': 'fl->fx',
        'fixnum->flonum': 'fx->fl', 'inexact': '->fl', 'exact': 'fl->exact-integer',
        'bitwise-arithmetic-shift': 'arithmetic-shift', 'isqrt': 'integer-sqrt', 'numref-q': 'q'}


def from_chez(e):
    if isinstance(e, list) and e:
        h = e[0]
        if h == 'let' and isinstance(e[1], Sym):
            return [h, e[1], [[b[0], from_chez(b[1])] for b in e[2]], from_chez(e[3])]
        h2 = Sym(CHEZ.get(h, h)) if isinstance(h, Sym) else h
        return [h2] + [from_chez(x) for x in e[1:]]
    return e


def fma(a, b, c):
    if not all(math.isfinite(x) for x in (a, b, c)):
        if math.isnan(a) or math.isnan(b) or math.isnan(c): return math.nan
        if (math.isinf(a) and b == 0) or (math.isinf(b) and a == 0): return math.nan
        p = a * b  # inf or finite (finite*finite may overflow: still the right inf)
        if math.isinf(a) or math.isinf(b):
            return p + c  # inf + -inf -> nan, as fma
        return c  # finite product + infinite c
    r = Fraction(a) * Fraction(b) + Fraction(c)
    if r == 0:
        pneg = (math.copysign(1, a) * math.copysign(1, b)) < 0
        if a * b == 0 and c == 0:
            return -0.0 if (pneg and math.copysign(1, c) < 0) else 0.0
        return 0.0
    try:
        return float(r)
    except OverflowError:
        return math.inf if r > 0 else -math.inf


def nextafter(a, b):
    return math.nextafter(a, b)


# ---------------------------------------------------------------- evaluator
class Prog:
    def __init__(self, text):
        forms = parse_all(text)
        assert forms and forms[0][0] == 'module'
        self.funs = {}
        self.lines = []  # (index, expr)
        for f in forms[0][3:]:
            if not isinstance(f, list) or not f: continue
            if f[0] == 'define' and isinstance(f[1], list) and str(f[1][0]).startswith('f') and f[1][0] not in ('enc',):
                self.funs[f[1][0]] = (f[1][1:], f[2])
            elif f[0] == 'o':
                a = f[2]
                if a[0] == 'lambda':                      # (lambda () e)
                    self.lines.append((f[1], a[2]))
                elif a[0] == 'vm-eval':                   # (vm-eval '(lambda () e)): Chez names
                    self.lines.append((f[1], from_chez(a[1][1][2])))
                else:                                     # (let ([fc (vm-eval '(lambda (p...) e))]) (lambda () (fc a...)))
                    lam = a[1][0][1][1][1]
                    name = Sym('fc%s' % f[1])
                    self.funs[name] = (lam[1], from_chez(lam[2]))
                    self.lines.append((f[1], [name] + a[2][2][1:]))

    def ev(self, e, env):
        if isinstance(e, Sym):
            if e in env: return env[e]
            raise Unspec()
        if not isinstance(e, list):
            return e
        h = e[0]
        if h == 'q': return self.ev(e[1], env)
        if h == 'if':
            c = self.ev(e[1], env)
            return self.ev(e[2], env) if c is not False else self.ev(e[3], env)
        if h == 'let' and isinstance(e[1], Sym):
            name, binds, body = e[1], e[2], e[3]
            params = [b[0] for b in binds]
            vals = [self.ev(b[1], env) for b in binds]
            depth = [0]

            def loop(*args):
                depth[0] += 1
                if depth[0] > 1000: raise Unspec()
                env2 = dict(env); env2.update(zip(params, args)); env2[name] = loop
                return self.ev(body, env2)
            return loop(*vals)
        if h in ('let', 'let*'):
            env2 = dict(env)
            for b in e[1]:
                env2[b[0]] = self.ev(b[1], env2 if h == 'let*' else env)
            return self.ev(e[2], env2)
        args = [self.ev(x, env) for x in e[1:]]
        if isinstance(h, Sym) and h in env and callable(env[h]):
            return env[h](*args)
        if h in self.funs:
            ps, body = self.funs[h]
            return self.ev(body, dict(zip(ps, args)))
        return prim(h, args)

    def expected(self):
        out = []
        for i, e in self.lines:
            try:
                out.append((i, enc(self.ev(e, {}))))
            except Err:
                out.append((i, 'err'))
            except Unspec:
                out.append((i, None))
            except (OverflowError, MemoryError, RecursionError):
                out.append((i, None))
        return out


def enc(v):
    s = enc1(v)
    n = len(s)
    return s[:50] + '~' + str(n) + '~' + s[n - 50:] if n > 120 else s


def enc1(v):
    if isbool(v): return '#t' if v else '#f'
    if isfl(v):
        if math.isnan(v): return 'nan'
        if v == math.inf: return '+inf'
        if v == -math.inf: return '-inf'
        if v == 0.0 and math.copysign(1, v) < 0: return '-0'
        return 'f' + str(norm(Fraction(v)))
    if isexact(v): return 'e' + str(norm(Fraction(v)))
    if isinstance(v, str): return 's' + v
    raise Unspec()


def unwrite(s):
    # a Racket `write`n string: "..." with \\ \" \n \t escapes
    assert s[0] == '"' and s[-1] == '"'
    out = []; i = 1
    while i < len(s) - 1:
        c = s[i]
        if c == '\\':
            n = s[i + 1]; i += 2
            out.append({'n': '\n', 't': '\t', '\\': '\\', '"': '"', 'r': '\r'}.get(n, n))
        else:
            out.append(c); i += 1
    return ''.join(out)


AREA_SKIP = {'q', 'if', 'let', 'let*'}


def area_of(e, funs):
    """first primitive in preorder (stable name for the signature)"""
    if isinstance(e, list) and e:
        h = e[0]
        if h in funs:
            r = area_of(funs[h][1], funs)
            if r: return r
        elif isinstance(h, Sym) and h not in AREA_SKIP and not h.startswith('loop'):
            return h
        for x in e[1:]:
            if isinstance(x, list):
                for y in (x if (h == 'let' or h == 'let*') and x and isinstance(x[0], list) else [x]):
                    r = area_of(y, funs)
                    if r: return r
    return None


def sanitize(op):
    m = {'+': 'add', '-': 'sub', '*': 'mul', '/': 'div', '=': 'eq', '<': 'lt', '>': 'gt',
         '<=': 'le', '>=': 'ge'}
    if op in m: return m[op]
    s = op.replace('->', '-to-').replace('/', '-').replace('?', '').replace('*', 'mul').replace('+', 'add')
    s = s.replace('<=', 'le').replace('>=', 'ge').replace('<', 'lt').replace('>', 'gt').replace('=', 'eq')
    return re.sub(r'[^a-z0-9-]', '', s) or 'num'


def check(text, line):
    """-> ('pass'|'skip'|'gen', ...) or ('fail', kind, index, area, detail)"""
    p = Prog(text)
    f = line.rstrip('\n').split('\t')
    if f[0] != 'ok':
        if f[0] == 'exn':
            return ('gen', 'module raised: ' + '\t'.join(f[2:])[:300])
        return ('skip', f[0])
    got = {}
    for l in unwrite(f[1]).split('\n'):
        if l:
            k, _, v = l.partition(' ')
            got[int(k)] = v
    errs = []
    for i, exp in p.expected():
        if got.get(i) == 'err': errs.append(str(i))
        if exp is None: continue
        g = got.get(i)
        if g is None: return ('gen', 'line %d missing' % i)
        if g != exp:
            kind = 'error' if 'err' in (g, exp) else 'value'
            e = dict(p.lines)[i]
            return ('fail', kind, i, sanitize(area_of(e, p.funs) or 'num'),
                    'line %d: racket %s, expected %s' % (i, g[:300], exp[:300]))
    # indices of lines that raised (left out of the unsafe re-run: UB there)
    return ('pass', ','.join(errs) or '-')


def main():
    cmd = sys.argv[1]
    sys.setrecursionlimit(20000)
    sys.set_int_max_str_digits(0)
    if cmd == 'eval':
        for i, e in Prog(open(sys.argv[2]).read()).expected():
            print(i, e if e is not None else '(unspecified)')
    elif cmd == 'check':
        r = check(open(sys.argv[2]).read(), sys.stdin.readline())
        print(' '.join(str(x) for x in r))
        sys.exit(1 if r[0] == 'fail' else 0 if r[0] == 'pass' else 2)
    elif cmd == 'server':
        inp = sys.stdin.buffer
        while True:
            h = inp.readline()
            if not h: break
            text = inp.read(int(h)).decode()
            m = int(inp.readline())
            line = inp.read(m).decode()
            try:
                r = check(text, line)
            except Exception as ex:  # reference bug: never a finding
                r = ('gen', 'numref.py exception %r' % ex)
            sys.stdout.write('\t'.join(str(x).replace('\t', ' ').replace('\n', ' ') for x in r) + '\n')
            sys.stdout.flush()


if __name__ == '__main__':
    main()
